package settle

// 摘要の桁切れによる取り違えを防ぐ。
//
// ── なぜスコアリングの外側に置くか ──
//
// 銀行明細の摘要は桁数制限で切れる。長い社名が切れると、短い別会社の
// 名前と【完全一致】することがある。実測（学習済み・12桁で切断）:
//
//	見本印刷工業 の摘要 ﾌﾘｺﾐ ﾐﾎﾝｲﾝｻﾂｺｳｷﾞｮｳ → 12桁 → ﾌﾘｺﾐ ﾐﾎﾝｲﾝｻﾂ
//	  見本印刷（別会社）  score=100.0  lev=1.00 jac=1.00 pre=1.00
//	  見本印刷工業（正解）score= 51.4  lev=0.58 jac=0.55 pre=0.58
//
// 誤ったほうが全成分1.00の完全一致になる。重みは合計1.0なので、
// 配分をどう変えても100点のままで、100点を超える配点は存在しない。
// prefix の重みを 0.0〜0.5 で振って実測したが、逆転件数も
// 「誤りが95以上」の件数も1件も動かなかった。
//
// つまり重みでは原理的に勝てない。だから対策を採点の外に置く。
//
// ── 何を見るか ──
//
// 危険なのは「切れた摘要が、別の実在する取引先と完全一致する」場合だけ。
// これはマスタを引けば事前に分かる。摘要の正規形で始まる取引先が
// 2件以上あれば、その摘要は原理的に一意に定まらない。
//
// 【重要】情報が破壊されている以上、正しいほうを選び直すことはできない。
// できるのは「自動で確定させない」ことだけ。人に回す。

import "fmt"

// 候補として残りうる組み合わせのうち、金額＋日付の寄与の最良と最悪。
//
//	金額  完全一致100 か、銀行の手数料差引70（候補生成が他を弾く）
//	日付  銀行 {100,80,60,30} / カード {100,80,30} / 読めず50
//
// 上限値を両側から挟むのに使う。
const (
	bestRest  = wAmount*100 + wDate*100 // 60.0
	worstRest = wAmount*70 + wDate*30   // 32.0
	// 判定が >= なので、天井は合計でこの点数ぶん手前に置く。
	// これが無いと、閾値90のとき上限値75で合計がちょうど90.0になり、
	// 「>= 上限」で自動承認を通ってしまう。頭打ちが無効になる。
	capMarginTotal = 1.0
	// 上限値の既定の頭。閾値が高くても、これ以上には上げない。
	// 曖昧な候補が、曖昧でない候補より上に来ないようにするため。
	capDefault = 80.0
)

// CapFor は曖昧な摘要に当てる名前スコアの上限値を返す。
//
// ok=false は「頭打ちでは守れない」。天井が床を下回る設定
// （上限95/下限70、上限80/下限55 など）で起きる。
// そのときは頭打ちを諦め、判定を直接 StatusReview にする。
func CapFor(upper, lower float64) (float64, bool) {
	// 天井: 金額・日付が満点でも自動承認に届かない
	ceil := (upper - bestRest - capMarginTotal) / wName
	// 床: 金額・日付が最悪でも却下に落とさない
	floor := (lower - worstRest) / wName
	if ceil < floor {
		return 0, false
	}
	c := ceil
	if c > capDefault {
		c = capDefault
	}
	if c < floor {
		c = floor
	}
	return c, true
}

// Ambiguity は曖昧と判定した根拠。監査ログと画面に出す。
//
// 「なぜ自動承認されなかったのか」を後から説明できないと、
// 現場は結果を信用しない。数字ではなく、引いた条件と当たった相手を残す。
type Ambiguity struct {
	// 摘要の正規形。前方一致に使った文字列そのもの。
	Norm string `json:"norm"`
	// 前方一致した取引先の名前。2件以上あるから曖昧と判定した。
	Matched []string `json:"matched"`
	// 適用した上限値。頭打ちできなかったときは 0。
	Cap float64 `json:"cap"`
	// 頭打ちで守れず、判定を直接「要確認」にしたか。
	Forced bool `json:"forced"`
}

func (a Ambiguity) Why() string {
	list := ""
	for i, m := range a.Matched {
		if i > 0 {
			list += "／"
		}
		list += m
	}
	s := fmt.Sprintf("摘要「%s」が途中で切れているため、%d件の取引先に一致します（%s）。",
		a.Norm, len(a.Matched), list)
	if a.Forced {
		return s + "どれか一つに定まらないので、人の確認に回しました。"
	}
	return s + fmt.Sprintf("名前スコアを%.0fで頭打ちにし、自動では確定しません。", a.Cap)
}

// CapName は名前スコアに上限を当てる。採点する前に呼ぶ。
//
// 【重要】スコアを下げるのではなく、上限を設ける。
// 上限より低いスコアはそのまま。金額・日付・合算の式には触らない。
//
// 採点後の Scored をいじらないのは、合算を計算し直すのに
// 元の伝票（金額・日付）が要るため。ここで式を書き直すと、
// Score と2つの実装ができて、いつか必ずずれる。
func CapName(name, cap float64, ok bool) float64 {
	if !ok || name <= cap {
		return name
	}
	return cap
}
