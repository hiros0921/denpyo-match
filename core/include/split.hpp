// 1枚の紙に複数の伝票が写っているとき、伝票ごとに切り分ける。
//
// なぜ要るか
//
//   受領側で一番多いのはレシートで、現場はレシートを何枚も台紙に貼るか、
//   まとめてスキャンする。実物の「レシートサンプル_10枚まとめ.pdf」は
//   1ページに2枚が横に並んでいた。
//
//   分けずに読むと、1件の伝票の中で項目が混ざる。実測:
//     取引先名 サンプルマート（左のレシート）
//     金額     ¥5,395        （右のレシート）
//   正解は左が ¥1,258、右が見本石油サービス。
//   どちらの項目にも「読めなかった」印は付かないので、
//   スコアは高いまま出る。閾値では止まらない。
//
// なぜ空白の帯で切るか
//
//   罫線でも枠でもなく、空白で切る。レシートに枠は無く、
//   紙が別々である以上、間には必ず何も無い帯ができる。
//   実測（150dpi・A4）:
//     レシート2枚並び   中央に 19px（内容幅の2.4%）の帯
//     請求書1枚         中央付近に縦の帯なし
//
// 【重要】切りすぎるほうが、切らないより悪い。
//
//   1枚の請求書を2つに割ると、両方とも金額も取引先も欠けた伝票になり、
//   2件とも人が見ることになる。しかも元が1枚だったことは画面から分からない。
//   だから「端に寄った帯」「片側の中身が薄い帯」では切らない。
//   迷ったら切らない側に倒す。
