-- 012: 1つの伝票に同じ順位の候補を2行作らせない
--
-- なぜ必要か
--
--   影響範囲の画面は、照合結果に「1位の候補」を結合して件数を数える。
--   同じ伝票に rank=1 が2行あると、その伝票が2件として数えられる。
--   見直しの範囲を決めるための画面なので、件数が水増しされるのは困る。
--
--   現時点で重複は0件だが、それを保証している仕組みが無かった。
--   第6段階で「2台のワーカーが同じ伝票を処理する」実例を踏んでいるので、
--   起きない前提にはしない。
--
--   保存側は再処理のたびに DELETE してから入れ直す作りだが、
--   その DELETE が抜けた場合、あるいは2台が同時に書いた場合に重複する。
--   アプリで気をつけるのではなく、DBが受け付けないようにする。

BEGIN;

CREATE UNIQUE INDEX match_candidates_document_rank_key
  ON match_candidates (document_id, rank);

COMMIT;
