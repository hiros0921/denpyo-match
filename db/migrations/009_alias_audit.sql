-- 009: 覚えた表記の追加・取り消しを監査ログに残せるようにする
--
-- なぜ必要か（実測で分かったこと）
--
--   承認画面で候補を1つ押すと、その伝票に書かれていた表記が
--   別名として貯まる。これは「使うほど当たるようになる」仕組みの中心で、
--   実測でも効果が出た。
--     コウヨウエ業（OCRが工をエと誤読）を人が1件直した結果
--       却下 5件 → 4件、自動承認 12件 → 13件、誤承認は依然ゼロ
--
--   ところが同じ強さで逆にも効く。第7段階の検証中に、
--   誤った組み合わせ（株式会社コウヨウ工業 に「ナンセイ運輸561」）を
--   1件登録してしまった。結果:
--     株式会社ナンセイ運輸561an の照会で、誤った取引先が同点1位になった
--       1位 株式会社コウヨウ工業     81.27  ← ナンセイ運輸561 で一致
--       2位 株式会社ナンセイ運輸561  81.27  ← 正解
--   自動承認には至らなかった（81.27 < 上限95）ので人が気付ける状態だったが、
--   放置すればこの取引先はずっと当たらなくなる。
--
--   押し間違いは現場で必ず起きる。起きることを前提に、
--   「誰が・いつ・何を覚えさせたか」を残し、取り消せるようにする。
--
-- 覚えたことの取り消しは、覚えたことの削除ではない。
-- partner_aliases の行は消えるが、覚えた事実と取り消した事実は
-- 監査ログに残る（監査ログは追記のみで消せない）。

BEGIN;

ALTER TABLE audit_logs DROP CONSTRAINT audit_logs_action_check;
ALTER TABLE audit_logs ADD CONSTRAINT audit_logs_action_check
  CHECK (action IN (
    'create',        -- 伝票の受付
    'auto_approve',  -- 閾値による自動承認（threshold_id が必須）
    'needs_review',  -- 人の確認待ちへ回した
    'approve',       -- 人が承認
    'update',        -- 人が修正
    'reject',        -- 却下
    'learn_alias',   -- 表記を覚えさせた
    'forget_alias'   -- 覚えた表記を取り消した
  ))
  NOT VALID;   -- 既存行は検査しない。追記のみの表なので直せないため

COMMIT;
