-- 011: 誤認識の影響範囲を辿るための索引
--
-- 何を辿れるようにするか
--
--   誤りが見つかったとき、現場が最初に知りたいのは
--   「同じ誤りが何件に及んだか」と「そのうち何件が人の目を通らずに確定したか」。
--   後者が本質。要確認に回っていれば人が見ているが、
--   自動承認された分は誰も見ていない。
--
--   起点は3つある。
--     ① 取引先        この取引先に紐づいた伝票は全部おかしいかもしれない
--     ② 覚えた表記    誤って覚えた表記が、どの伝票に効いたか
--     ③ 閾値設定      緩すぎた設定の期間に自動承認されたものを洗い直す
--
-- 実測（50万件の照合候補・1万件の照合結果）
--
--   ① 取引先で辿る    0.039 ms   既存の索引が効く
--   ③ 閾値設定で辿る  0.424 ms   既存の索引が効く
--   ② 表記で辿る     46.050 ms   ← 全件走査。索引が無い
--
-- ② だけが桁違いに遅い。しかも「誤って覚えた表記の影響を調べる」という、
-- いちばん急いで知りたい場面で使うものなので、ここが遅いのは困る。

BEGIN;

-- 一致した表記で辿る。
--
-- rank=1 に限る部分索引にする。2位以下は結果を決めていないので、
-- 影響範囲を調べるときの対象にならない。
-- 全件を対象にすると索引が50倍の大きさになり、書き込みも重くなる。
CREATE INDEX match_candidates_matched_form
  ON match_candidates ((score_detail->>'matched'))
  WHERE rank = 1;

-- 閾値設定で辿る。
--
-- 今は decision の索引が代わりに使われていて速いが、
-- それは閾値設定が1件しか無いため。設定が増えると効かなくなる。
-- 「どの設定で自動承認したか」を辿るのは、この製品の中心にある要件なので、
-- たまたま速い状態に頼らない。
CREATE INDEX match_results_threshold_decided
  ON match_results (threshold_id, decided_at DESC)
  WHERE threshold_id IS NOT NULL;

COMMIT;
